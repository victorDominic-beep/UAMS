const express = require("express")
const { authenticate } = require("../../../middleware/auth")
const { requirePermissions, requireRoles } = require("../../../middleware/authorize")
const { validateBody } = require("../../../middleware/validate")
const HttpError = require("../../../utils/httpError")
const service = require("../services/insuranceService")
const { createInsuranceSchema, updateInsuranceSchema, listInsuranceSchema } = require("../validation/schemas")

const router = express.Router()
const run = (handler, status = 200) => (req, res, next) => Promise.resolve(handler(req)).then((data) => res.status(status).json({ success: true, data })).catch(next)
router.use(authenticate)
router.get("/", requirePermissions("assets.read"), (req, res, next) => {
  const result = listInsuranceSchema.safeParse(req.query)
  if (!result.success) return next(new HttpError(400, "Invalid insurance query", result.error.issues))
  return Promise.resolve(service.listPolicies(result.data)).then((data) => res.status(200).json({ success: true, data })).catch(next)
})
router.post("/", requireRoles("WORKS_INSPECTION_OFFICER"), requirePermissions("insurance.track"), validateBody(createInsuranceSchema), run((req) => service.createPolicy(req.body, req.user, req.ip), 201))
router.get("/:id", requirePermissions("assets.read"), run((req) => service.getPolicy(req.params.id)))
router.patch("/:id", requireRoles("WORKS_INSPECTION_OFFICER"), requirePermissions("insurance.track"), validateBody(updateInsuranceSchema), run((req) => service.updatePolicy(req.params.id, req.body, req.user, req.ip)))
module.exports = router
